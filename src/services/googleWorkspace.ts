export const sendPodcastViaGmail = async (
  recipientEmail: string,
  subject: string,
  podcastTitle: string,
  transcriptSnippet: string,
  durationSec: number
): Promise<{ success: boolean; id: string }> => {
  const token = getAccessToken();
  if (!token) throw new Error('Not authenticated with Google Workspace');

  const minutes = Math.floor(durationSec / 60);
  const seconds = Math.floor(durationSec % 60);
  const durationStr = `${minutes}:${seconds.toString().padStart(2, '0')}`;

  const emailLines = [
    `To: ${recipientEmail}`,
    `Subject: =?UTF-8?B?${btoa(unescape(encodeURIComponent(subject)))}?=`,
    'Content-Type: text/html; charset=UTF-8',
    '',
    `<!DOCTYPE html>
    <html dir="auto">
    <head><meta charset="utf-8"></head>
    <body style="font-family: Arial, sans-serif; line-height: 1.6; color: #1e293b; background-color: #f8fafc; padding: 20px;">
      <div style="max-width: 600px; margin: 0 auto; background: #ffffff; padding: 24px; border-radius: 12px; border: 1px solid #e2e8f0;">
        <h2 style="color: #d97706; margin-top: 0;">🎙️ ${podcastTitle}</h2>
        <p><strong>Duration:</strong> ${durationStr} min</p>
        <p><strong>Generated By:</strong> Podcast AI Local Studio (Multi-Speaker Engine)</p>
        <hr style="border: none; border-top: 1px solid #e2e8f0; margin: 20px 0;" />
        <h4 style="margin-bottom: 8px;">Transcript Preview:</h4>
        <div style="background: #f1f5f9; padding: 14px; border-radius: 8px; font-size: 14px; color: #334155;">
          ${transcriptSnippet.replace(/\n/g, '<br/>')}
        </div>
        <p style="margin-top: 24px; font-size: 12px; color: #64748b;">
          Created offline with Podcast AI Local Studio.
        </p>
      </div>
    </body>
    </html>`,
  ];

  const rawEmail = emailLines.join('\r\n');
  const base64EncodedEmail = btoa(unescape(encodeURIComponent(rawEmail)))
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');

  const sendRes = await fetch('https://gmail.googleapis.com/gmail/v1/users/me/messages/send', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ raw: base64EncodedEmail }),
  });

  if (!sendRes.ok) {
    const err = await sendRes.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to send email via Gmail');
  }

  const result = await sendRes.json();
  return { success: true, id: result.id };
};

/* ===================================================================
 * FIRESTORE SYNC & PERSISTENCE
 * =================================================================== */

export const saveEpisodeToFirestore = async (
  userId: string,
  episodeId: string,
  title: string,
  durationSec: number,
  voices: string[],
  script: ScriptSegment[],
  driveFileId?: string
) => {
  const episodeRef = doc(firestore, `users/${userId}/episodes/${episodeId}`);
  await setDoc(episodeRef, {
    id: episodeId,
    userId,
    title,
    durationSec,
    voices,
    scriptJson: JSON.stringify(script),
    driveFileId: driveFileId || '',
    createdAt: new Date().toISOString(),
  });
};

export const fetchUserSavedEpisodes = async (userId: string) => {
  const episodesRef = collection(firestore, `users/${userId}/episodes`);
  const snapshot = await getDocs(episodesRef);
  return snapshot.docs.map(docSnap => docSnap.data());
};
