export interface GoogleDriveFile {
  id: string;
  name: string;
  mimeType: string;
  size?: string;
  modifiedTime?: string;
}

export const listGoogleDriveFiles = async (): Promise<GoogleDriveFile[]> => {
  const token = getAccessToken();
  if (!token) throw new Error('Not authenticated with Google Workspace');

  const res = await fetch(
    'https://www.googleapis.com/drive/v3/files?pageSize=25&q=trashed=false&fields=files(id,name,mimeType,size,modifiedTime)&orderBy=modifiedTime desc',
    {
      headers: { Authorization: `Bearer ${token}` },
    }
  );

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to list Google Drive files');
  }

  const data = await res.json();
  return data.files || [];
};

export const readGoogleDriveFileContent = async (fileId: string): Promise<string> => {
  const token = getAccessToken();
  if (!token) throw new Error('Not authenticated with Google Workspace');

  const res = await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}?alt=media`, {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (!res.ok) {
    throw new Error('Failed to download Google Drive file content');
  }

  return await res.text();
};

export const uploadPodcastToDrive = async (
  title: string,
  audioBlobUrl: string,
  script: ScriptSegment[]
): Promise<{ fileId: string; webViewLink?: string }> => {
  const token = getAccessToken();
  if (!token) throw new Error('Not authenticated with Google Workspace');

  // Fetch the audio blob from the local blob URL
  const audioResponse = await fetch(audioBlobUrl);
  const audioBlob = await audioResponse.blob();

  const boundary = '-------PodcastAIDriveUpload' + Math.random().toString(36).substring(2);
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const metadata = {
    name: `${title || 'Podcast Episode'}.wav`,
    mimeType: 'audio/wav',
    description: `Generated by Podcast AI Studio with ${script.length} speaker turns.`,
  };

  const metadataPart =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    '\r\n';

  const audioBytes = await audioBlob.arrayBuffer();

  // Construct multipart body
  const multipartPrefix = new TextEncoder().encode(
    metadataPart +
      delimiter +
      'Content-Type: audio/wav\r\n' +
      'Content-Transfer-Encoding: binary\r\n\r\n'
  );
  const multipartSuffix = new TextEncoder().encode(closeDelimiter);

  const fullPayload = new Uint8Array(
    multipartPrefix.byteLength + audioBytes.byteLength + multipartSuffix.byteLength
  );
  fullPayload.set(multipartPrefix, 0);
  fullPayload.set(new Uint8Array(audioBytes), multipartPrefix.byteLength);
  fullPayload.set(multipartSuffix, multipartPrefix.byteLength + audioBytes.byteLength);

  const uploadRes = await fetch(
    'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,webViewLink',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': `multipart/related; boundary=${boundary}`,
      },
      body: fullPayload,
    }
  );

  if (!uploadRes.ok) {
    const err = await uploadRes.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to upload podcast to Google Drive');
  }

  const uploadData = await uploadRes.json();
  return { fileId: uploadData.id, webViewLink: uploadData.webViewLink };
};

